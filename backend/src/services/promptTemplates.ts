/**
 * ===== 两阶段提示词工程核心说明 =====
 * 
 * 阶段1（总结笔记生成）:
 * - 一阶提示词：STAGE1_SYSTEM_PROMPT（固定在后端，不可更改）
 *   作用：确保总结笔记的质量和结构
 * - 二阶提示词：customSummaryPrompt（用户在前端定义）
 *   作用：指导总结的风格和重点方向
 * - 函数：draftSummaryNotes()
 *
 * 阶段2（JSON结构化）:
 * - 一阶提示词：STAGE2_SYSTEM_PROMPT（固定在后端，不可更改）
 *   作用：确保JSON格式符合前端模式
 * - 二阶提示词：customJsonPrompt（用户在前端定义）
 *   作用：指导JSON内容的侧重点和标签分类
 * - 函数：synthesizeAnalysisResult()
 *
 * 架构设计：
 * 后端维护"一阶提示词" → 保证系统稳定性和格式一致性
 * 前端维护"二阶提示词" → 用户完全控制输出内容
 * 历史记录 → 完全动态，只有用户生成的才保存
 */

// ============ 一阶提示词（底层格式提示） ============

export const STAGE1_SYSTEM_PROMPT = `
你是一位专业的工作分析师。你的任务是基于用户的指导和提供的桌面活动分析数据，生成一份结构清晰、洞察深刻的总结笔记。

重要原则：
1. 分析而非流水账 - 重点关注"做了什么"和"取得了什么成果"
2. 前后呼应 - 将相关活动串联起来，展现工作的完整逻辑
3. 量化数据 - 如果有时间占比、工作密度等数据，应当量化表述
4. 洞察优先 - 在提出事实之前，先表达洞察和结论
5. 中文输出 - 清晰、简洁、专业的中文表述

你将收到以下信息：
- 用户的自定义指导（二阶提示词，指导总结方向）
- 活动卡片数据（已分析的工作段落）
- 原始观察数据（视频转录结果）

请根据用户指导，结合这些数据，生成一份1-3段落的总结笔记。
`;

